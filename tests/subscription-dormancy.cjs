'use strict';
const assert=require('node:assert/strict');
const {INACTIVE_DAYS,snapshot,renewalDecision,reactivationDecision}=require('../lib/subscription-dormancy.cjs');
assert.equal(INACTIVE_DAYS,30);
const from='2026-10-01T12:00:00.000Z';
const paidThrough='2026-11-01T12:00:00.000Z';
const atDays=d=>new Date(Date.parse(from)+d*86400000).toISOString();
assert.equal(snapshot({now:atDays(29),lastActivityAt:from,paidThrough}).phase,'active');
let thirty=snapshot({now:atDays(30),lastActivityAt:from,paidThrough});
assert.equal(thirty.phase,'dormant');assert.equal(thirty.permitAutomaticRenewal,false);
assert.equal(thirty.hasPrepaidAccess,true,'Already paid access is preserved');
assert.equal(snapshot({now:atDays(32),lastActivityAt:from,paidThrough}).hasPrepaidAccess,false);
assert.equal(renewalDecision({renewalAt:paidThrough,paidThrough,lastActivityAt:from}).action,'stop_no_charge_dormant');
assert.equal(renewalDecision({renewalAt:paidThrough,paidThrough,lastActivityAt:from}).shouldCharge,false);
assert.equal(renewalDecision({renewalAt:paidThrough,paidThrough,lastActivityAt:atDays(30)}).shouldCharge,true,'Activity within last 30 days allows renewal');
assert.equal(renewalDecision({renewalAt:paidThrough,paidThrough,lastActivityAt:atDays(30),cancelRequestedAt:atDays(30)}).shouldCharge,false,'Cancel always wins');
assert.equal(snapshot({now:atDays(4),lastActivityAt:from,paidThrough,cancelRequestedAt:atDays(3)}).permitAutomaticRenewal,false);
assert.equal(snapshot({now:atDays(4),lastActivityAt:from,paidThrough,cancelRequestedAt:atDays(3)}).hasPrepaidAccess,true);
assert.equal(reactivationDecision({now:atDays(30),lastActivityAt:from,paidThrough}).action,'restore_prepaid_access_without_charge');
assert.equal(reactivationDecision({now:atDays(30),lastActivityAt:from,paidThrough}).chargeNow,false);
assert.equal(reactivationDecision({now:atDays(32),lastActivityAt:from,paidThrough}).action,'new_checkout_required');
assert.equal(reactivationDecision({now:atDays(32),lastActivityAt:from,paidThrough}).requiresRenewalConsent,true);
const annualThrough='2027-10-01T12:00:00.000Z';
assert.equal(snapshot({now:atDays(55),lastActivityAt:from,paidThrough:annualThrough}).hasPrepaidAccess,true,'Annual membership is not erased by dormancy');
assert.equal(reactivationDecision({now:atDays(55),lastActivityAt:from,paidThrough:annualThrough}).chargeNow,false,'No second charge during prepaid annual term');
assert.equal(renewalDecision({renewalAt:annualThrough,paidThrough:annualThrough,lastActivityAt:from}).shouldCharge,false);
assert.throws(()=>snapshot({now:from,lastActivityAt:atDays(1),paidThrough}),/future/);
assert.throws(()=>renewalDecision({renewalAt:from,lastActivityAt:from,paidThrough}),/boundary/);
console.log('Passed: 30-day dormancy, renewal cut-off, manual cancellation, prepaid access, annual cycle, explicit restart and clock guards.');
